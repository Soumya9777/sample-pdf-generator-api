from io import BytesIO
from pathlib import Path
import re

from fastapi import FastAPI, File, Form, HTTPException, UploadFile
from fastapi.responses import StreamingResponse
from PIL import Image, ImageOps
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.utils import ImageReader
from reportlab.pdfgen import canvas

app = FastAPI(
    title="Sample PDF Generator API",
    description="Creates clearly marked SAMPLE/DEMO PDFs from a name and photo.",
    version="1.0.0",
)

MAX_PHOTO_BYTES = 8 * 1024 * 1024
ALLOWED_TYPES = {"image/jpeg", "image/png", "image/webp"}

def safe_filename(name: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_-]+", "_", name.strip()).strip("_")
    return (cleaned or "sample")[:60]

@app.get("/")
def root():
    return {
        "message": "Sample PDF Generator API is running",
        "docs": "/docs",
        "endpoint": "POST /generate-pdf",
        "note": "Output is a generic SAMPLE/DEMO document, not an official identity or health card."
    }

@app.post("/generate-pdf")
async def generate_pdf(
    name: str = Form(..., min_length=1, max_length=100),
    photo: UploadFile = File(...)
):
    name = name.strip()
    if not name:
        raise HTTPException(status_code=422, detail="Name cannot be empty.")

    if photo.content_type not in ALLOWED_TYPES:
        raise HTTPException(status_code=415, detail="Upload a JPG, PNG, or WEBP image.")

    raw = await photo.read()
    if not raw:
        raise HTTPException(status_code=400, detail="The uploaded photo is empty.")
    if len(raw) > MAX_PHOTO_BYTES:
        raise HTTPException(status_code=413, detail="Photo must be 8 MB or smaller.")

    try:
        img = Image.open(BytesIO(raw)).convert("RGB")
        img = ImageOps.fit(img, (480, 600), method=Image.Resampling.LANCZOS)
    except Exception:
        raise HTTPException(status_code=400, detail="Could not read that image. Try a JPG or PNG.")

    output = BytesIO()
    page_w, page_h = A4
    c = canvas.Canvas(output, pagesize=A4)
    navy = colors.HexColor("#183B68")
    pale = colors.HexColor("#F2F6FB")
    ink = colors.HexColor("#1F2937")
    muted = colors.HexColor("#64748B")

    # Generic design intentionally distinct from government-issued cards.
    c.setFillColor(pale)
    c.rect(0, 0, page_w, page_h, fill=1, stroke=0)

    margin = 42
    card_x, card_y = margin, page_h - 330
    card_w, card_h = page_w - 2 * margin, 270

    c.setFillColor(colors.white)
    c.roundRect(card_x, card_y, card_w, card_h, 16, fill=1, stroke=0)
    c.setFillColor(navy)
    c.roundRect(card_x, card_y + card_h - 68, card_w, 68, 16, fill=1, stroke=0)
    c.rect(card_x, card_y + card_h - 68, card_w, 16, fill=1, stroke=0)

    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 18)
    c.drawString(card_x + 22, card_y + card_h - 31, "PERSONAL PROFILE")
    c.setFont("Helvetica", 10)
    c.drawString(card_x + 22, card_y + card_h - 49, "CUSTOM SAMPLE DOCUMENT")

    photo_x, photo_y, photo_w, photo_h = card_x + 24, card_y + 68, 112, 140
    c.drawImage(ImageReader(img), photo_x, photo_y, width=photo_w, height=photo_h, preserveAspectRatio=True, mask="auto")
    c.setStrokeColor(colors.HexColor("#D6DEE8"))
    c.rect(photo_x, photo_y, photo_w, photo_h, fill=0, stroke=1)

    text_x = photo_x + photo_w + 24
    c.setFillColor(muted)
    c.setFont("Helvetica-Bold", 9)
    c.drawString(text_x, card_y + 190, "NAME")
    c.setFillColor(ink)
    c.setFont("Helvetica-Bold", 16)
    # Keep long names inside the card.
    display_name = name if len(name) <= 28 else name[:25] + "..."
    c.drawString(text_x, card_y + 168, display_name)
    c.setFillColor(muted)
    c.setFont("Helvetica-Bold", 9)
    c.drawString(text_x, card_y + 130, "DOCUMENT TYPE")
    c.setFillColor(ink)
    c.setFont("Helvetica", 11)
    c.drawString(text_x, card_y + 111, "SAMPLE / DEMO ONLY")
    c.setFillColor(muted)
    c.setFont("Helvetica", 8)
    c.drawString(text_x, card_y + 84, "Not an official ID or credential")

    # Prominent diagonal watermark.
    c.saveState()
    c.translate(page_w / 2, page_h / 2)
    c.rotate(35)
    c.setFillColor(colors.Color(0.78, 0.12, 0.12, alpha=0.17))
    c.setFont("Helvetica-Bold", 54)
    c.drawCentredString(0, 0, "SAMPLE DEMO")
    c.restoreState()

    c.setFillColor(navy)
    c.setFont("Helvetica-Bold", 14)
    c.drawString(margin, 125, "About this file")
    c.setFillColor(ink)
    c.setFont("Helvetica", 10)
    c.drawString(margin, 105, "This PDF was generated automatically from the name and photo supplied.")
    c.drawString(margin, 89, "It is a demonstration template and has no official status or identity function.")
    c.setFillColor(muted)
    c.setFont("Helvetica", 8)
    c.drawString(margin, 48, "Generated by Sample PDF Generator API")
    c.drawRightString(page_w - margin, 48, "SAMPLE / DEMO ONLY")
    c.showPage()
    c.save()
    output.seek(0)

    filename = f"{safe_filename(name)}_sample_demo.pdf"
    return StreamingResponse(
        output,
        media_type="application/pdf",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'}
    )
